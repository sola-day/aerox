defmodule Aerox.ATProto.SpaceAlphaGoldenTest do
  @moduledoc """
  DESIGN §12.1/§12.7: bit-exactness against the *published* Spaces alpha
  (`@atproto/space@0.0.0-spaces-alpha-20260818163953`, the `bulletin` pin):
  set-hash elements and states, the commit context/MAC/signature, the
  two-root CAR and the space tokens, from `test/golden/space/alpha.json`
  (generated by `test/harness/gen-space-alpha-goldens.mjs` with that package).
  """
  use Aerox.GoldenCase, async: true
  alias Aerox.ATProto.{CID, Crypto, DagCBOR}
  alias Aerox.ATProto.Space.{LtHash, Repo, SignedCommit}
  alias Aerox.PDS.Space.Credentials

  defp hex(bin), do: Base.encode16(bin, case: :lower)
  defp unhex(hex), do: Base.decode16!(hex, case: :lower)

  defp golden, do: json_golden!("space/alpha.json")

  defp records(g) do
    Map.new(g["records"], fn r ->
      {Repo.key(r["collection"], r["rkey"]), {CID.parse!(r["cid"]), r["record"]}}
    end)
  end

  test "records: CIDs, element strings, set-hash states and an update" do
    g = golden()

    for r <- g["records"] do
      assert hex(DagCBOR.encode(r["record"])) == r["bytes"]
      assert CID.to_string(Repo.record_cid(r["record"])) == r["cid"]
      assert LtHash.record_element(r["collection"], r["rkey"], r["record"]) in g["elements"]
    end

    assert Enum.map(
             g["records"],
             &LtHash.record_element(&1["collection"], &1["rkey"], &1["record"])
           ) ==
             g["elements"]

    g["records"]
    |> Enum.zip(g["steps"])
    |> Enum.reduce(LtHash.new(), fn {r, step}, acc ->
      acc = LtHash.add(acc, LtHash.record_element(r["collection"], r["rkey"], r["record"]))
      assert LtHash.to_hex(acc) == step["state"]
      assert hex(LtHash.digest(acc)) == step["digest"]
      acc
    end)

    state = Repo.recompute(records(g))
    assert LtHash.to_hex(state.set_hash) == g["state"]
    assert hex(LtHash.digest(state.set_hash)) == g["digest"]
    assert hex(DagCBOR.encode(Repo.index(state))) == g["indexBytes"]

    u = g["update"]

    {:ok, [prepared], updated} =
      Repo.format_commit(state, [
        %{action: :update, collection: "my.bulletin.post", rkey: u["rkey"], record: u["record"]}
      ])

    assert CID.to_string(prepared.cid) == u["cid"] and CID.to_string(prepared.prev) == u["prev"]
    assert LtHash.to_hex(updated.set_hash) == u["state"]
    assert hex(LtHash.digest(updated.set_hash)) == u["digest"]
  end

  test "commit: ctx bytes, HKDF-expand key, MAC and signature verify; ours verifies the same way" do
    g = golden()
    c = g["commit"]
    ctx = %{space: c["ctx"]["space"], author: c["ctx"]["author"], rev: c["ctx"]["rev"]}
    ikm = unhex(c["ikm"])
    hash = unhex(c["hash"])
    assert hex(SignedCommit.ctx_bytes(ctx, ikm)) == c["ctxBytes"]
    assert hex(SignedCommit.mac(ikm, unhex(c["ctxBytes"]), hash)) == c["mac"]

    theirs = %{
      ver: 1,
      hash: hash,
      ikm: ikm,
      mac: unhex(c["mac"]),
      sig: unhex(c["sig"]),
      rev: ctx.rev
    }

    assert SignedCommit.verify(theirs, ctx, g["key"]["did"])
    refute SignedCommit.verify(theirs, %{ctx | author: "did:plc:other"}, g["key"]["did"])
    refute SignedCommit.verify(theirs, %{ctx | rev: "3mv4fihuqwc2z"}, g["key"]["did"])
    assert hex(DagCBOR.encode(SignedCommit.to_lex(theirs))) == c["commitBytes"]
    assert SignedCommit.from_lex(SignedCommit.to_lex(theirs)) == theirs

    # our own commit with the same key and ikm: identical MAC; the signature
    # is ours (not deterministic here) but verifies under the alpha's did:key
    kp = Crypto.import(:k256, unhex(g["key"]["privateKeyHex"]))
    assert Crypto.did_key(kp) == g["key"]["did"]
    ours = SignedCommit.create(hash, ctx, kp, ikm: ikm)
    assert hex(ours.mac) == c["mac"]
    assert SignedCommit.verify(ours, ctx, g["key"]["did"])
  end

  test "CAR: our export is byte-identical to serializeRepo, and imports back" do
    g = golden()
    c = g["commit"]
    state = Repo.recompute(records(g))

    theirs = %{
      ver: 1,
      hash: unhex(c["hash"]),
      ikm: unhex(c["ikm"]),
      mac: unhex(c["mac"]),
      sig: unhex(c["sig"]),
      rev: c["ctx"]["rev"]
    }

    assert hex(Repo.export_car(state, theirs)) == g["car"]
    assert {:ok, commit, imported} = Repo.import_car(unhex(g["car"]))
    assert commit == theirs
    assert imported.set_hash == state.set_hash
    assert Map.keys(imported.records) == Map.keys(state.records)
  end

  test "tokens: the alpha's delegation token and credential verify; ours carry the same claims" do
    g = golden()
    t = g["tokens"]
    now = t["now"] + 1
    resolve = fn _iss, _force -> {:ok, g["key"]["did"]} end
    space = g["commit"]["ctx"]["space"]
    author = g["commit"]["ctx"]["author"]

    assert {:ok, %{iss: ^author, sub: ^space, aud: aud}} =
             Credentials.verify_delegation(t["delegation"],
               now: now,
               resolve_key: resolve,
               sub: space,
               aud: t["delegationAud"],
               replay: false
             )

    assert aud == t["delegationAud"]

    assert {:error, {"JwtExpired", _}} =
             Credentials.verify_delegation(t["delegation"],
               now: now + 120,
               resolve_key: resolve,
               replay: false
             )

    assert {:ok, %{sub: ^space, jkt: "NzbLsXh8uDCcd-6MNwXF4W_7noWXFZAfHkxZsRGC9Xs"}} =
             Credentials.verify_credential(t["credential"], now: now, resolve_key: resolve)

    kp = Crypto.import(:k256, unhex(g["key"]["privateKeyHex"]))
    {:ok, their_header, their_payload} = Credentials.peek(t["delegation"])

    ours =
      Credentials.create_delegation(%{iss: author, space: space, aud: t["delegationAud"]}, kp,
        now: t["now"]
      )

    {:ok, our_header, our_payload} = Credentials.peek(ours)
    assert our_header == their_header
    assert Map.drop(our_payload, ["jti"]) == Map.drop(their_payload, ["jti"])
  end
end
