import Config

# Databases. Postgres 18 runs in Docker on loopback (compose.yaml, DEV_PLAN
# §1.1). Each repo connects as its own role (DESIGN §4.6); the roles are created
# by docker/postgres/init and each has exactly the privileges its service needs.
db_host = System.get_env("DATABASE_HOST", "127.0.0.1")
db_port = String.to_integer(System.get_env("DATABASE_PORT", "5433"))
# AEROX_DB_SUFFIX="_drill" points a second dev server at restored copies of
# both databases (the restore drill, docs/OPS.md §3).
db_suffix = System.get_env("AEROX_DB_SUFFIX", "")

for {repo, role, database} <- [
      {Aerox.PDS.Repo, "aerox_pds", "aerox_pds"},
      {Aerox.PLC.Repo, "aerox_plc", "aerox_core"},
      {Aerox.Relay.Repo, "aerox_relay", "aerox_core"},
      {Aerox.AppView.Repo, "aerox_appview", "aerox_core"},
      {Aerox.Labeler.Repo, "aerox_labeler", "aerox_core"}
    ] do
  config :aerox, repo,
    username: role,
    password: System.get_env("DATABASE_ROLE_PASSWORD", role),
    hostname: db_host,
    port: db_port,
    database: database <> db_suffix,
    stacktrace: true,
    show_sensitive_data_on_connection_error: true,
    # four repos share one small box: STRUCTURE §7 asks for explicit sizing
    pool_size: String.to_integer(System.get_env("AEROX_POOL_SIZE", "10"))
end

# The endpoint binds to loopback by default, so a plain checkout is not exposed
# to the network. On a box that fronts the dev server with Traefik (DEV_PLAN
# §1.2) set AEROX_BIND_IP to the address Traefik can reach — on this host that
# is the `multica` bridge gateway, which is private to that bridge — and PHX_HOST
# to the name Traefik terminates TLS for. Never bind 0.0.0.0: there is no host
# firewall, so that would publish the dev server on the public interface.
bind_ip =
  System.get_env("AEROX_BIND_IP", "127.0.0.1")
  |> String.split(".")
  |> Enum.map(&String.to_integer/1)
  |> List.to_tuple()

# Public URL. Behind Traefik the scheme is https on 443 even though the endpoint
# itself speaks plain http on 4000; atproto clients read this back as the
# service endpoint, so it has to be the externally reachable one.
url_config =
  case System.get_env("PHX_HOST") do
    nil -> [host: "localhost"]
    host -> [host: host, scheme: "https", port: 443]
  end

# For development, we disable any cache and enable
# debugging and code reloading.
