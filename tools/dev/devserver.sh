#!/bin/bash
# The primary dev server (DEV_PLAN §1.2) — pds/plc/relay/appview/labeler/
# jetstream on <dev-domain>, port 4000.
#
# Dev secrets are NOT in the repo (DEV_PLAN §1.3). This script generates them
# once into tmp/dev.env — which .gitignore keeps out — and every mix command
# picks them up from there (config/dev.exs reads the same file). Delete the
# file to roll every dev key and password; the PLC rotation key is the one to
# think twice about, since dev DIDs already name it.
#
#   tools/dev/devserver.sh
set -euo pipefail
export PATH="$HOME/.local/share/mise/shims:$HOME/.local/bin:$PATH"
cd "$(dirname "$0")/../.."
set -a; . ./.envrc; set +a

mkdir -p tmp
if [ ! -e tmp/dev.env ]; then
  umask 077
  {
    echo "# Generated by tools/dev/devserver.sh — throwaway secrets for this dev box."
    echo "AEROX_PLC_ROTATION_KEY_HEX=$(openssl rand -hex 32)"
    echo "AEROX_OAUTH_KEY_HEX=$(openssl rand -hex 32)"
    echo "AEROX_APPVIEW_SIGNING_KEY_HEX=$(openssl rand -hex 32)"
    echo "AEROX_PDS_ADMIN_PASSWORD=$(openssl rand -hex 16)"
    echo "AEROX_RELAY_ADMIN_PASSWORD=$(openssl rand -hex 16)"
    echo "AEROX_LABELER_ADMIN_PASSWORD=$(openssl rand -hex 16)"
  } > tmp/dev.env
  echo "tools/dev/devserver.sh: generated tmp/dev.env"
fi
set -a; . ./tmp/dev.env; set +a

exec elixir --sname aerox --cookie "${AEROX_NODE_COOKIE:-aerox-dev}" -S mix phx.server
